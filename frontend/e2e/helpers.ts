import { createHmac, randomBytes } from "node:crypto";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { type APIRequestContext, type BrowserContext, expect, type Page } from "@playwright/test";

const here = dirname(fileURLToPath(import.meta.url));
const AUTH_FILE = join(here, ".auth", "owner.json"); // git-ignored; generated by j01 for the isolated E2E stack

export type Creds = { email: string; password: string; totpSecret?: string };

export function newOwnerCreds(): Creds {
  const creds = { email: "e2e-owner@example.com", password: `e2e-${randomBytes(12).toString("hex")}` };
  mkdirSync(dirname(AUTH_FILE), { recursive: true });
  writeFileSync(AUTH_FILE, JSON.stringify(creds));
  return creds;
}

export function ownerCreds(): Creds {
  if (!existsSync(AUTH_FILE)) throw new Error("Run j01 (first run) first: it creates the E2E owner.");
  return JSON.parse(readFileSync(AUTH_FILE, "utf-8")) as Creds;
}

export function updateOwnerCreds(change: Partial<Creds>) {
  writeFileSync(AUTH_FILE, JSON.stringify({ ...ownerCreds(), ...change }));
}

function csrfFrom(cookies: { name: string; value: string }[]) {
  return cookies.find((c) => c.name === "dops_csrf")?.value ?? "";
}

/** JSON API call that shares the browser context's cookies (and sends CSRF like the SPA). */
export async function api(ctx: BrowserContext | APIRequestContext, method: string, path: string, body?: unknown, base = "/api") {
  const request = "request" in ctx ? ctx.request : ctx;
  const cookies = "cookies" in ctx ? await ctx.cookies() : [];
  const res = await request.fetch(`${base}${path}`, {
    method, data: body === undefined ? undefined : body,
    headers: { "Content-Type": "application/json", "X-CSRF-Token": csrfFrom(cookies) },
  });
  const text = await res.text();
  return { status: res.status(), json: text ? JSON.parse(text) : null };
}

export async function signIn(page: Page, creds: Creds = ownerCreds()) {
  const { totpSecret, ...body } = creds;
  const r = await api(page.context(), "POST", "/auth/login", { ...body, totp_code: totpSecret ? totp(totpSecret) : undefined });
  expect(r.status, "owner sign-in").toBe(200);
}

/** Completes the step-up dialog if the action asked for it. */
export async function confirmStepUp(page: Page, password = ownerCreds().password) {
  const dialog = page.getByRole("dialog", { name: "Confirm it's you" });
  await dialog.waitFor({ state: "visible", timeout: 10_000 });
  await dialog.getByLabel("Password").fill(password);
  const secret = ownerCreds().totpSecret;
  if (secret) await dialog.getByLabel("Authenticator code (if enabled)").fill(totp(secret));
  await dialog.getByRole("button", { name: "Confirm" }).click();
  await expect(dialog).toBeHidden();
}

/** For actions where step-up may still be fresh (valid 5 minutes): confirm only if the dialog appears. */
export async function maybeConfirmStepUp(page: Page) {
  const dialog = page.getByRole("dialog", { name: "Confirm it's you" });
  if (await dialog.waitFor({ state: "visible", timeout: 3000 }).then(() => true, () => false)) await confirmStepUp(page);
}

export async function stepUpViaApi(page: Page, password = ownerCreds().password) {
  const secret = ownerCreds().totpSecret;
  expect((await api(page.context(), "POST", "/auth/step-up", { password, totp_code: secret ? totp(secret) : undefined })).status).toBe(200);
}

export async function instrumentId(page: Page, symbol: string): Promise<string> {
  const r = await api(page.context(), "GET", "/markets/instruments");
  return (r.json as { id: string; symbol: string }[]).find((i) => i.symbol === symbol)!.id;
}

/** RFC 6238 TOTP (SHA-1, 30 s, 6 digits) for the authenticator journey. */
export function totp(base32: string, at = Date.now()): string {
  const alphabet = "ABCDEFGHIJKLMNOPQRSTUVWXYZ234567";
  let bits = "";
  for (const ch of base32.replace(/=+$/, "").toUpperCase()) bits += alphabet.indexOf(ch).toString(2).padStart(5, "0");
  const key = Buffer.from(bits.match(/.{8}/g)!.map((b) => parseInt(b, 2)));
  const counter = Buffer.alloc(8);
  counter.writeBigUInt64BE(BigInt(Math.floor(at / 1000 / 30)));
  const h = createHmac("sha1", key).update(counter).digest();
  const o = h[h.length - 1] & 0xf;
  const code = ((h.readUInt32BE(o) & 0x7fffffff) % 1_000_000).toString();
  return code.padStart(6, "0");
}

export async function noHorizontalOverflow(page: Page, where = page.url()) {
  const r = await page.evaluate(() => {
    const inner = window.innerWidth;
    let worst = "";
    let right = 0;
    for (const el of Array.from(document.body.querySelectorAll<HTMLElement>("*"))) {
      const b = el.getBoundingClientRect();
      if (b.right > inner + 1 && b.right > right && getComputedStyle(el).position !== "fixed") {
        let clipped = false; // inside a horizontally scrollable/clipping ancestor is fine
        for (let p = el.parentElement; p; p = p.parentElement) {
          const ox = getComputedStyle(p).overflowX;
          if (ox === "auto" || ox === "scroll" || ox === "hidden" || ox === "clip") { clipped = true; break; }
        }
        if (!clipped) { right = b.right; worst = `${el.tagName.toLowerCase()}.${(el.className || "").toString().slice(0, 80)} "${(el.textContent || "").trim().slice(0, 40)}"`; }
      }
    }
    return { scroll: document.documentElement.scrollWidth, inner, worst };
  });
  expect(r.scroll, `${where}: page wider than viewport (${r.scroll} > ${r.inner}); widest: ${r.worst}`).toBeLessThanOrEqual(r.inner + 1);
}

export async function waitForDecisionStatus(page: Page, id: string, statuses: string[], timeoutMs = 120_000) {
  await expect.poll(async () => (await api(page.context(), "GET", `/decisions/${id}`)).json.status, { timeout: timeoutMs, intervals: [1000, 2000, 3000] })
    .toMatch(new RegExp(`^(${statuses.join("|")})$`));
}
